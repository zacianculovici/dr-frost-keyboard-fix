(() => {
  const attachedFields = new WeakSet();
  let currentField = null;

  const clickKeyboardButton = (mq, position) => {
    const button = document.querySelector(
      `#keyboard-button-section-lessmain > span:nth-child(${position}) button`
    );

    if (!button) {
      console.error(`Dr Frost keyboard fix: virtual keyboard button ${position} not found.`);
      return;
    }

    button.click();
    mq.focus();
  };

  const attachToField = (field) => {
    if (!field || attachedFields.has(field)) {
      return;
    }

    // Find the required MathQuill instance and editable input.
    const mq = window.jQuery?.data(field, 'mathField');
    const input = field.querySelector('[tabindex="0"]');

    if (!mq || !input) {
      return;
    }

    attachedFields.add(field);
    currentField = field;
    field.dataset.drFrostKeyboardFix = 'active';
    document.querySelector('#virtual-keyboard')?.style.setProperty('display', 'none', 'important');

    input.addEventListener('keydown', (event) => {
      /*
      These either enter the required symbol/number/letter through MathQuill
      or click the corresponding button on the virtual keyboard.
      */
      if (event.altKey && event.shiftKey && (event.key === '6' || event.code === 'Digit6')) {
        event.preventDefault();
        event.stopPropagation();
        clickKeyboardButton(mq, 5);
        return;
      }

      if (event.key === '^') {
        event.preventDefault();
        event.stopPropagation();
        clickKeyboardButton(mq, 8);
        return;
      }

      if (event.key === 'Backspace') {
        event.preventDefault();
        mq.keystroke('Backspace');
        return;
      }

      if (event.key === 'ArrowLeft' || event.key === 'ArrowRight') {
        event.preventDefault();
        mq.keystroke(event.key.replace('Arrow', '').toLowerCase());
        return;
      }

      if (event.key === 'Enter') {
        event.preventDefault();
        field.closest('form')?.requestSubmit();
        return;
      }

      if (
        event.key.length === 1 &&
        !event.ctrlKey &&
        !event.metaKey &&
        !event.altKey
      ) {
        event.preventDefault();
        mq.write(event.key);
      }
    });

    input.focus();
    mq.focus();
  };

  const attachToCurrentField = () => {
    const field = document.querySelector('#expression-answer');
    if (!field) {
      return;
    }

    if (attachedFields.has(field)) {
      currentField = field;
      field.dataset.drFrostKeyboardFix = 'active';
      return;
    }

    attachToField(field);
  };

  document.addEventListener('click', (event) => {
    if (!event.target.closest('#nextquestion-button')) {
      return;
    }

    // Mark the old field before Dr Frost replaces it with the next question.
    if (currentField) {
      currentField.dataset.drFrostKeyboardFix = 'completed';
    }

    setTimeout(attachToCurrentField, 0);
  });

  new MutationObserver(attachToCurrentField).observe(document.body, {
    childList: true,
    subtree: true
  });

  attachToCurrentField();
})();
